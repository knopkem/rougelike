    pub fn by_id(id: u32) -> Option<&'static MonsterDef> {
        Self::ALL.iter().find(|d| d.id == id)
    }

    /// All non-unique monsters that can appear at the given depth.
    pub fn for_depth(depth: u32) -> Vec<&'static MonsterDef> {
        Self::ALL
            .iter()
            .filter(|d| !d.unique && depth >= d.min_depth && depth <= d.max_depth)
            .collect()
    }

    /// The boss for a given depth, if any.
    pub fn boss_for_depth(depth: u32) -> Option<&'static MonsterDef> {
        Self::ALL
            .iter()
            .find(|d| d.unique && d.min_depth == depth && d.max_depth == depth)
    }
