//! Monster definitions: ~45 species across 5 tiers, plus named bosses.

use crate::core::color::Color;
use serde::{Deserialize, Serialize};

/// A special ability a monster can use.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Ability {
    /// Drain life on a successful hit.
    Drain,
    /// Spit poison at range.
    PoisonSpit,
    /// Petrify the player on a successful hit.
    Petrify,
    /// Paralyze the player on a successful hit.
    Paralyze,
    /// Put the player to sleep.
    Sleep,
    /// Confuse the player.
    Confusion,
    /// Blink (teleport) a short distance.
    Blink,
    /// Summon additional monsters.
    Summon,
    /// Split into smaller copies on death.
    Split,
    /// Regenerate HP each turn.
    Regen,
    /// Enrage below 30% HP (attack bonus).
    Enrage,
    /// Cone of fire breath.
    FireBreath,
    /// Paralyzing eye ray.
    EyeRay,
}

impl Ability {
    pub fn name(self) -> &'static str {
        match self {
            Ability::Drain => "drains your life",
            Ability::PoisonSpit => "spits poison",
            Ability::Petrify => "petrifies you",
            Ability::Paralyze => "paralyzes you",
            Ability::Sleep => "puts you to sleep",
            Ability::Confusion => "confuses you",
            Ability::Blink => "blinks",
            Ability::Summon => "summons reinforcements",
            Ability::Split => "splits",
            Ability::Regen => "regenerates",
            Ability::Enrage => "enrages",
            Ability::FireBreath => "breathes fire",
            Ability::EyeRay => "fires an eye ray",
        }
    }
}

/// A static monster definition.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub struct MonsterDef {
    pub id: u32,
    pub name: &'static str,
    pub glyph: char,
    pub color: Color,
    /// Tier 1..=5.
    pub tier: u8,
    /// Minimum depth this monster appears at.
    pub min_depth: u32,
    /// Maximum depth this monster appears at (u32::MAX for no cap).
    pub max_depth: u32,
    /// Base hit points.
    pub hp: u32,
    /// Base attack (to-hit bonus).
    pub attack: i32,
    /// Damage die (sides).
    pub damage_die: u32,
    /// Damage bonus.
    pub damage_bonus: i32,
    /// Armor class.
    pub ac: i32,
    /// XP awarded on death.
    pub xp: u32,
    /// Whether this monster can attack at range.
    pub ranged: bool,
    /// Special abilities.
    pub abilities: &'static [Ability],
    /// Whether this is a unique (named, boss) monster.
    pub unique: bool,
}

