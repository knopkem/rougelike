#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn catalog_has_expected_species() {
        assert!(MonsterDef::ALL.len() >= 45);
        let non_unique: Vec<_> = MonsterDef::ALL.iter().filter(|d| !d.unique).collect();
        assert!(non_unique.len() >= 45);
    }

    #[test]
    fn by_id_roundtrip() {
        for d in MonsterDef::ALL {
            assert_eq!(MonsterDef::by_id(d.id).unwrap().id, d.id);
        }
    }

    #[test]
    fn for_depth_respects_range() {
        let d1 = MonsterDef::for_depth(1);
        assert!(!d1.is_empty());
        for d in d1 {
            assert!(d.min_depth <= 1 && d.max_depth >= 1);
            assert!(!d.unique);
        }
    }

    #[test]
    fn bosses_on_expected_depths() {
        assert!(MonsterDef::boss_for_depth(5).is_some());
        assert!(MonsterDef::boss_for_depth(10).is_some());
        assert!(MonsterDef::boss_for_depth(15).is_some());
        assert!(MonsterDef::boss_for_depth(20).is_some());
        assert!(MonsterDef::boss_for_depth(25).is_some());
        assert!(MonsterDef::boss_for_depth(3).is_none());
    }

    #[test]
    fn unique_ids_are_distinct() {
        use std::collections::HashSet;
        let ids: HashSet<u32> = MonsterDef::ALL.iter().map(|d| d.id).collect();
        assert_eq!(ids.len(), MonsterDef::ALL.len());
    }
}
